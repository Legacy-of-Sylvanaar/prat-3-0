Test.start()
local m, server, flush = Test.module(), Test.server, Test.flush
local passed = 0
local function check(name, callback)
	callback()
	flush()
	passed = passed + 1
	print("PASS " .. name)
end
check("empty group does not alter the main dock", function()
	assert(not m.group:IsShown())
	assert(#GENERAL_CHAT_DOCK.DOCKED_CHAT_FRAMES == 3 and ChatFrame1:IsVisible())
	assert(m.command == "pratgroup" and m:GetDescription())
end)
check("General, Combat Log, unused and protected windows are excluded", function()
	m:AddWindow(1); m:AddWindow(2); m:AddWindow(7)
	ChatFrame6.protected = true; m:AddWindow(6); ChatFrame6.protected = nil
	assert(#m.db.char.members == 0)
end)
local originalPoint = {ChatFrame3:GetPoint(1)}
check("add Party and Raid without changing filters or left selection", function()
	m:AddWindow(3); m:AddWindow(4)
	assert(#m.db.char.members == 2 and m.db.char.selected == 4)
	assert(ChatFrame1:IsVisible() and GENERAL_CHAT_DOCK.selected == ChatFrame1)
	assert(ChatFrame4:IsVisible() and not ChatFrame3:IsVisible())
	assert(ChatFrame3:IsShown() and server[3].shown and server[4].shown)
	assert(server[3].channels[1] == "CHANNEL_3")
	assert(not ChatFrame3Tab:IsVisible() and not ChatFrame4.ResizeButton:IsVisible())
end)
check("switching uses independent visibility and input focus", function()
	m:SelectWindow(3)
	assert(ChatFrame3:IsVisible() and not ChatFrame4:IsVisible())
	assert(Test.lastActive() == ChatFrame3.editBox and ChatFrame4.editBox.deactivated)
	assert(server[4].shown and ChatFrame4:IsShown())
end)
check("inactive tabs receive messages and show unread indicators", function()
	ChatFrame4:AddMessage("party test")
	assert(ChatFrame4.messages[1] == "party test" and m.active[4].unread)
	assert(m.active[4].button.label.text == "Raid" and m.active[4].button.glow.FlashAnim:IsPlaying())
	m:SelectWindow(4)
	assert(not m.active[4].unread and not m.active[4].button.glow.FlashAnim:IsPlaying())
end)
check("native tab click hooks and context menus remain usable", function()
	local called
	ChatFrame3Tab:SetScript("OnClick", function(tab, button) called = true; FCF_Tab_OnClick(tab, button) end)
	local button = m.active[3].button
	button:GetScript("OnClick")(button, "LeftButton")
	assert(called and m.db.char.selected == 3)
	button:GetScript("OnClick")(button, "RightButton")
	assert(testMenuID == 3)
end)
check("Prat SideTabs cannot expose native tabs by reparenting", function()
	ChatFrame3Tab:SetParent(UIParent); ChatFrame3Tab:Show()
	assert(ChatFrame3Tab:GetParent() == m.hidden and not ChatFrame3Tab:IsVisible())
	if FCF_UpdateChatFrameParent then FCF_UpdateChatFrameParent(ChatFrame3) end
	assert(ChatFrame3:GetParent() == m.active[3].holder)
end)
check("Blizzard restoration cannot close an inactive group window", function()
	FloatingChatFrame_Update(4)
	assert(server[4].shown and #server[4].channels == 1 and m.active[4])
	flush()
	assert(not ChatFrame4:IsVisible())
	local _, relative = ChatFrame4:GetPoint(1)
	assert(relative == m.group)
end)
check("tab ordering persists and boundary moves are ignored", function()
	m:MoveWindow(4, -1)
	assert(m.db.char.members[1].id == 4)
	m:MoveWindow(4, -1)
	assert(m.db.char.members[1].id == 4)
	m:MoveWindow(4, 1)
	assert(m.db.char.members[2].id == 4)
end)
check("rename updates the saved identity and button label", function()
	FCF_SetWindowName(ChatFrame4, "Raid Group"); flush()
	assert(m:GetEntry(4).name == "Raid Group" and m.active[4].button.label.text == "Raid Group")
end)
check("Alt-Z preserves registered windows and channel filters", function()
	UIParent:Hide()
	assert(not ChatFrame3:IsVisible() and server[3].shown and server[4].shown)
	UIParent:Show()
	assert(ChatFrame3:IsVisible() and #server[3].channels == 1)
end)
check("fullscreen UI parents are respected", function()
	if not FCF_SetFullScreenFrame then return end
	local full = CreateFrame("Frame", nil, UIParent)
	FCF_SetFullScreenFrame(full); flush()
	assert(m.group:GetParent() == full)
	FCF_ClearFullScreenFrame(); flush()
	assert(m.group:GetParent() == UIParent)
end)
check("combat permits ordinary tab switching but blocks membership edits", function()
	Test.combat(true)
	m:AddWindow(6); m:RemoveWindow(3); m:MoveWindow(4, -1)
	assert(not m:GetEntry(6) and m:GetEntry(3) and m.db.char.members[1].id == 3)
	assert(m:SelectWindow(4) and ChatFrame4:IsVisible())
	Test.combat(false)
end)
check("removing a standalone window restores its geometry and controls", function()
	m:RemoveWindow(3)
	assert(not m.active[3] and not m:GetEntry(3) and ChatFrame3:IsVisible())
	assert(ChatFrame3:GetWidth() == 403 and ChatFrame3:GetHeight() == 203)
	local point, parent, relative, x, y = ChatFrame3:GetPoint(1)
	assert(point == originalPoint[1] and parent == originalPoint[2] and relative == originalPoint[3] and x == originalPoint[4] and y == originalPoint[5])
	assert(ChatFrame3Tab:IsVisible() and ChatFrame3.ResizeButton:GetParent() == ChatFrame3)
end)
check("taking and returning a main-dock tab restores docking", function()
	m:AddWindow(5)
	assert(not ChatFrame5.isDocked and #GENERAL_CHAT_DOCK.DOCKED_CHAT_FRAMES == 2)
	m:RemoveWindow(5)
	assert(ChatFrame5.isDocked and #GENERAL_CHAT_DOCK.DOCKED_CHAT_FRAMES == 3)
	assert(not ChatFrame5:IsVisible() and ChatFrame1:IsVisible())
end)
check("external docking removes a window from the secondary group", function()
	m:AddWindow(3); FCF_DockFrame(ChatFrame3, 4)
	assert(not m:GetEntry(3) and not m.active[3] and ChatFrame3.isDocked)
	assert(ChatFrame3Tab:GetParent() ~= m.hidden)
end)
check("closing an inactive tab really closes its persisted slot", function()
	m:AddWindow(6); m:SelectWindow(4)
	FCF_Close(ChatFrame6)
	assert(not m:GetEntry(6) and not m.active[6] and not server[6].shown)
	assert(#server[6].channels == 0 and m.db.char.selected == 4)
end)
check("closed slots can be reused without silently rejoining the group", function()
	FCF_SetWindowName(ChatFrame6, "New window"); server[6].shown = true; ChatFrame6:Show()
	FloatingChatFrame_Update(6); flush()
	assert(not m:GetEntry(6) and not m.active[6])
end)
check("resize and lock settings update every member", function()
	m:AddWindow(6)
	m.db.char.width, m.db.char.height = 650, 260
	m.db.char.locked = true; m:Layout()
	assert(ChatFrame4:GetWidth() == 650 and ChatFrame6:GetHeight() == 260)
	assert(not m.resize:IsShown())
	m.db.char.locked = false; m:Layout()
	assert(m.resize:IsShown())
end)
check("drag end saves a stable UIParent position", function()
	m.moving = true; m.group.left, m.group.bottom = 1200, 220
	m:StopMoving()
	assert(m.db.char.point == "BOTTOMLEFT" and m.db.char.x == 1200 and m.db.char.y == 220)
end)
check("disable restores windows; enable keeps saved membership and order", function()
	local members = Test.clone(m.db.char.members)
	m.enabled = false; m:OnModuleDisable()
	assert(not m.group:IsShown() and ChatFrame4:IsVisible() and ChatFrame6:IsVisible())
	assert(ChatFrame4Tab:GetParent() ~= m.hidden)
	assert(#m.db.char.members == #members)
	m.enabled = true; m:OnModuleEnable(); flush()
	assert(m.active[4] and m.active[6] and m.group:IsShown())
	assert(m.db.char.members[1].id == members[1].id)
end)
check("stale saved names are rejected before startup rename hooks can adopt them", function()
	m.enabled = false; m:OnModuleDisable()
	server[6].name = "Recycled slot"
	m.enabled = true; m:OnModuleEnable()
	FCF_SetWindowName(ChatFrame6, "Recycled slot")
	flush()
	assert(not m:GetEntry(6) and not m.active[6] and m.active[4])
end)
check("duplicate saved IDs are removed", function()
	m.enabled = false; m:OnModuleDisable()
	table.insert(m.db.char.members, Test.clone(m.db.char.members[1]))
	m.enabled = true; m:OnModuleEnable(); flush()
	assert(#m.db.char.members == 1)
end)
check("startup in combat waits to restore membership", function()
	m.enabled = false; m:OnModuleDisable()
	Test.combat(true); m.enabled = true; m:OnModuleEnable(); flush()
	assert(not m.active[4] and m.restorePending)
	Test.combat(false); m:PLAYER_REGEN_ENABLED()
	assert(m.active[4])
end)
check("closing the final tab hides the group", function()
	FCF_Close(ChatFrame4)
	assert(#m.db.char.members == 0 and not m.group:IsShown())
end)
check("logout restores native windows while retaining the next-login layout", function()
	server[4].shown = true; ChatFrame4:Show(); server[4].channels = {"RAID"}
	m:AddWindow(3); m:AddWindow(4)
	local selected = m.db.char.selected
	m:PLAYER_LOGOUT()
	assert(not next(m.active) and not m.group:IsShown())
	assert(#m.db.char.members == 2 and m.db.char.selected == selected)
	assert(ChatFrame3.isDocked and not ChatFrame4.isDocked and server[4].shown)
	assert(ChatFrame3Tab:GetParent() ~= m.hidden and ChatFrame4Tab:IsVisible())
	m:OnModuleEnable(); flush()
	assert(m.active[3] and m.active[4] and m.db.char.selected == selected)
end)
check("native artwork, selected state and hover fading", function()
	local tab = m.active[4].button
	assert(tab.template == "ChatTabArtTemplate" and tab.ActiveLeft:IsShown())
	assert(not m.active[3].button.ActiveLeft:IsShown())
	m:UpdateHover(2)
	assert(tab:GetAlpha() == 0.4 and m.active[3].button:GetAlpha() == 0.6 and m.resize:GetAlpha() == 0)
	tab.mouseOver = true; m:UpdateHover(0.2)
	assert(tab:GetAlpha() == 1 and m.resize:GetAlpha() == 1)
	tab.mouseOver = false
	ChatFrame3:AddMessage("Unread")
	m:UpdateHover(2)
	assert(m.active[3].button:GetAlpha() == 1 and m.active[3].button.glow:IsShown())
end)
check("tab dragging respects position lock and combat", function()
	local tab = m.active[4].button
	m.db.char.locked = true
	tab:GetScript("OnDragStart")(); assert(not m.moving)
	m.db.char.locked = false; Test.combat(true)
	tab:GetScript("OnDragStart")(); assert(not m.moving)
	Test.combat(false)
	tab:GetScript("OnDragStart")(); assert(m.moving)
	tab:GetScript("OnDragStop")(); assert(not m.moving)
end)
check("compact native tabs wrap without stretching across the window", function()
	local first, second = m.active[3].button, m.active[4].button
	m.db.char.width = 650; m:Layout()
	assert(first:GetWidth() < 160 and second:GetWidth() < 160)
	FCF_SetWindowName(ChatFrame3, "Long party chat window")
	FCF_SetWindowName(ChatFrame4, "Long raid chat window")
	m.db.char.width = 250; m:Layout()
	local _, _, _, x, y = second:GetPoint(1)
	assert(x == 0 and y > 3 and first:GetWidth() <= 160)
end)
print(string.format("%d tests passed", passed))
